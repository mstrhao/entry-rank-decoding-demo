"""Packaging only: omit sampled plotting coordinates, preserve every scalar score."""
import argparse,copy,json
from pathlib import Path


def compact(report):
    out=copy.deepcopy(report)
    for sensitivity in out['sensitivity']:
        for component in sensitivity['components']:
            component.pop('coverage_risk',None)
            for detection in component['detection'].values():
                detection.pop('roc',None);detection.pop('pr',None)
    out['packaging_note']='Compact report omits only sampled coverage-risk and ROC/PR plotting coordinates. Every scalar score, threshold criterion, operating point, sensitivity and original-window metric is retained. Full metrics.json is regenerated by run_optimized.py; plotted curves are retained in PNGs.'
    return out

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--input',required=True);p.add_argument('--output',required=True);a=p.parse_args()
    out=Path(a.output)
    if out.exists():raise FileExistsError('Do not overwrite packaged reports')
    out.write_text(json.dumps(compact(json.loads(Path(a.input).read_text())),indent=2)+'\n')
